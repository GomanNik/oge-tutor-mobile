import { expect, test } from '@playwright/test';

const dateAt = (days, hour = 14) => { const date = new Date(); date.setUTCDate(date.getUTCDate() + days); date.setUTCHours(hour, 0, 0, 0); return date.toISOString().slice(0, 16); };
for (const width of [390, 1365]) {
  test(`recurring lessons and confirmation on a real API at ${width}px`, async ({ page }, testInfo) => {
    test.skip(!process.env.SERIES_REAL_API_EMAIL || !process.env.SERIES_REAL_API_PASSWORD || process.env.CUTOVER_REAL_API === 'true', 'Disposable non-retired series fixture is required.');
    test.setTimeout(90000);
    await page.setViewportSize({ width, height: 900 });
    await page.goto('/');
    await page.getByLabel('Email', { exact: true }).fill(process.env.SERIES_REAL_API_EMAIL);
    await page.getByLabel('Пароль', { exact: true }).fill(process.env.SERIES_REAL_API_PASSWORD);
    await page.getByRole('button', { name: 'Войти', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Расписание', exact: true })).toBeVisible();
    const selector = page.getByRole('combobox', { name: 'Рабочее пространство и роль' });
    const teacherOption = await selector.locator('option').evaluateAll(options => options.find(option => option.value.endsWith(':teacher')).value);
    await selector.selectOption(teacherOption);
    await page.getByRole('button', { name: 'Расписание', exact: true }).click();
    await page.getByRole('tab', { name: 'Серии', exact: true }).click();
    await page.getByRole('combobox', { name: 'Курс серии' }).selectOption(`browser-series-course-${width}`);
    await page.getByRole('button', { name: 'Новая серия', exact: true }).click();
    const form = page.getByRole('form', { name: 'Новая серия', exact: true });
    const marker = `Серия ${width} ${Date.now()}`;
    const firstDay = width === 390 ? 20 : 30;
    await form.getByLabel('Тема', { exact: true }).fill(marker);
    await form.getByLabel('Первое локальное начало').fill(dateAt(firstDay));
    await form.getByLabel('Окончание серии').fill(dateAt(firstDay + 7).slice(0, 10));
    await form.getByRole('combobox', { name: 'Повторение', exact: true }).selectOption('daily');
    await form.getByLabel('Интервал', { exact: true }).fill('7');
    await form.getByRole('checkbox', { name: 'Ученик серии', exact: true }).check();
    await expect(form.getByRole('button', { name: 'Создать серию', exact: true })).toBeDisabled();
    await form.getByRole('button', { name: 'Предпросмотр серии', exact: true }).click();
    await expect(form.getByRole('heading', { name: 'Пакет готов', exact: true })).toBeVisible();
    await expect(form.locator('.series-preview-list > div')).toHaveCount(2);
    await page.screenshot({ path: testInfo.outputPath(`series-preview-${width}.png`), fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await form.getByRole('button', { name: 'Создать серию', exact: true }).click();
    await expect(form).toHaveCount(0);
    const row = page.locator('.series-item').filter({ hasText: marker });
    await expect(row).toBeVisible();
    await row.getByRole('button', { name: 'Изменить серию', exact: true }).click();
    const edit = page.getByRole('form', { name: 'Изменение серии', exact: true });
    await edit.getByLabel('Тема', { exact: true }).fill(`${marker} обновлена`);
    await edit.getByLabel('Причина изменения', { exact: true }).fill('Обновление будущих занятий');
    await edit.getByRole('button', { name: 'Предпросмотр серии', exact: true }).click();
    await expect(edit.locator('.series-preview-list > div')).toHaveCount(4);
    await edit.getByRole('button', { name: 'Применить изменения', exact: true }).click();
    await expect(edit).toHaveCount(0);
    await row.getByRole('button', { name: 'Приостановить', exact: true }).click();
    let action = page.getByRole('form', { name: 'Приостановить', exact: true });
    await action.getByLabel('Причина', { exact: true }).fill('Пауза до согласования расписания');
    await action.getByRole('button', { name: 'Предпросмотр изменений', exact: true }).click();
    await expect(action.getByRole('heading', { name: 'Пакет готов', exact: true })).toBeVisible();
    await action.getByRole('button', { name: 'Подтвердить', exact: true }).click();
    await expect(row.getByText('Приостановлена', { exact: true })).toBeVisible();
    await row.getByRole('button', { name: 'Отменить серию', exact: true }).click();
    action = page.getByRole('form', { name: 'Отменить серию', exact: true });
    await action.getByLabel('Причина', { exact: true }).fill('Завершение тестового расписания');
    await action.getByRole('button', { name: 'Предпросмотр изменений', exact: true }).click();
    await expect(action.locator('.series-preview-list > div')).toHaveCount(2);
    await action.getByRole('button', { name: 'Подтвердить', exact: true }).click();
    await expect(row.getByText('Отменена', { exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath(`series-list-${width}.png`) });
  });
}
